/* 把前端产物与 Capacitor 配置同步进 android 工程（替代 cap sync 的 update + copy 两步）。
 *
 * 为什么不用 cap sync：
 *   1. 本机 safe-delete 垫片会挡掉它「先删旧 assets 目录」那一步，且失败后不回滚 ——
 *      APK 照样 BUILD SUCCESSFUL，打进去的却是旧前端（实测踩过，从产物上极难发现）。
 *   2. capacitor.config.json 被 android/.gitignore 忽略，属生成物。忘了同步，原生层就读不到
 *      plugins 配置 —— 曾因此 CapacitorHttp 一直是关的，AI 直连在真机上被 CORS 全拦，
 *      而桌面端（Electron 主进程直连）一切正常，排查成本极高。
 *
 * 用法：node scripts/sync-android.mjs（npm run android:apk 已接上）
 */
import fs from 'node:fs'
import { loadConfigFromFile } from 'vite'

const DIST = 'dist'
const DST = 'android/app/src/main/assets/public'
const CFG = 'android/app/src/main/assets/capacitor.config.json'

/* 1) 配置：从 capacitor.config.ts 现算，保证与源码永远一致 */
const loaded = await loadConfigFromFile({ command: 'build', mode: 'production' }, 'capacitor.config.ts')
if (!loaded) throw new Error('读不到 capacitor.config.ts')
fs.mkdirSync('android/app/src/main/assets', { recursive: true }) // 全新克隆没有此目录（git 不跟踪空目录），直接写 config 会 ENOENT
fs.writeFileSync(CFG, JSON.stringify(loaded.config, null, '\t') + '\n')
console.log('[sync] config →', CFG, JSON.stringify(loaded.config.plugins ?? {}))

/* 2) 产物：以 dist 的资产名单为白名单，删掉旧 hash 再覆盖写
 *    （不能拿 index.html 的引用当白名单：按需 import() 的 chunk 不在 html 里） */
if (!fs.existsSync(DIST + '/assets')) throw new Error('dist 不存在，先跑 vite build')
const keep = new Set(fs.readdirSync(DIST + '/assets'))
let removed = 0
if (fs.existsSync(DST + '/assets')) { // 全新克隆没有旧产物目录，跳过清理（下一步 cpSync 会全量写入）
  for (const f of fs.readdirSync(DST + '/assets')) {
    if (!keep.has(f)) {
      fs.unlinkSync(DST + '/assets/' + f)
      removed++
    }
  }
}
fs.cpSync(DIST, DST, { recursive: true, force: true })
console.log('[sync] assets →', fs.readdirSync(DST + '/assets').join(', '), removed ? `（清掉 ${removed} 个旧文件）` : '')

/* 3) 插件接线（替代 cap sync update 的插件发现步骤）：
 *    - assets/capacitor.plugins.json：Bridge 启动读它自动注册插件类（PluginManager.loadPluginClasses，缺了插件就是 Web 空壳）；
 *    - capacitor.settings.gradle / app/capacitor.build.gradle：Gradle 侧模块接线，缺了 APK 编不过去（或编过但没插件）。
 *    三处都是 android/.gitignore 忽略的生成物（gradle 两文件除外，随仓跟踪），照 CLI 的生成规则现算：
 *    扫 node_modules 里带 capacitor.android 字段的依赖（@capacitor/* 与第三方 cap 插件同规则），
 *    从插件安卓源码提取 @CapacitorPlugin 类名（同 @capacitor/cli 的正则口径）。 */

const PLUGINS_JSON = 'android/app/src/main/assets/capacitor.plugins.json'
const SETTINGS_GRADLE = 'android/capacitor.settings.gradle'
const APP_BUILD_GRADLE = 'android/app/capacitor.build.gradle'

function listSources(dir, out = []) {
  if (!fs.existsSync(dir)) return out
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = dir + '/' + e.name
    if (e.isDirectory()) listSources(p, out)
    else if (['.java', '.kt'].includes(e.name.slice(e.name.lastIndexOf('.')))) out.push(p)
  }
  return out
}

const pkgJson = JSON.parse(fs.readFileSync('package.json', 'utf8'))
const capPlugins = []
for (const name of Object.keys({ ...pkgJson.dependencies, ...pkgJson.devDependencies })) {
  let pj
  try { pj = JSON.parse(fs.readFileSync(`node_modules/${name}/package.json`, 'utf8')) } catch { continue }
  if (pj.capacitor?.android?.src) {
    capPlugins.push({ id: name, path: pj.capacitor.android.src })
  } else if (pj.name === name && name.startsWith('cordova-')) {
    throw new Error(`cordova 插件 ${name} 需要手工接线（copyPluginsNativeFiles 流程本脚本未实现）`)
  }
}

const pluginEntries = []
for (const p of capPlugins) {
  const classRegex = /^@(?:CapacitorPlugin|NativePlugin)[\s\S]+?class ([\w]+)/gm
  const packageRegex = /^package ([\w.]+);?$/gm
  for (const src of listSources(`node_modules/${p.id}/${p.path}/src/main`)) {
    const content = fs.readFileSync(src, 'utf8')
    const classMatch = classRegex.exec(content)
    if (!classMatch) continue
    packageRegex.lastIndex = 0
    const packageMatch = packageRegex.exec(content.substring(0, classMatch.index))
    if (!packageMatch) throw new Error(`插件 ${p.id} 的 ${src} 解析不到 package`)
    pluginEntries.push({ pkg: p.id, classpath: `${packageMatch[1]}.${classMatch[1]}` })
  }
}

// gradle 模块名口径同 @capacitor/cli：'@capacitor/local-notifications' → 'capacitor-local-notifications'
const gradleName = id => id.replace('@', '').replace('/', '-')
fs.writeFileSync(PLUGINS_JSON, JSON.stringify(pluginEntries, null, '\t') + '\n')
fs.writeFileSync(SETTINGS_GRADLE, `// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN
// 本仓由 scripts/sync-android.mjs 生成（cap sync 在本机被禁用，见仓根 AGENTS.md），手工改动会被覆盖
include ':capacitor-android'
project(':capacitor-android').projectDir = new File('../node_modules/@capacitor/android/capacitor')
${capPlugins.map(p => `
include ':${gradleName(p.id)}'
project(':${gradleName(p.id)}').projectDir = new File('../node_modules/${p.id}/${p.path}')
`).join('')}`)
fs.writeFileSync(APP_BUILD_GRADLE, `// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN
// 本仓由 scripts/sync-android.mjs 生成（cap sync 在本机被禁用，见仓根 AGENTS.md），手工改动会被覆盖

android {
  compileOptions {
      sourceCompatibility JavaVersion.VERSION_21
      targetCompatibility JavaVersion.VERSION_21
  }
}

apply from: "../capacitor-cordova-android-plugins/cordova.variables.gradle"
dependencies {
${capPlugins.map(p => `    implementation project(':${gradleName(p.id)}')`).join('\n')}
}

if (hasProperty('postBuildExtras')) {
  postBuildExtras()
}
`)
console.log('[sync] 插件接线 →', capPlugins.map(p => p.id).join(', ') || '（无）',
  '· 注册类', pluginEntries.length, '个 →', PLUGINS_JSON)
